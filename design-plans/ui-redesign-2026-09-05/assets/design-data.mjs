function inferPlatform(route) {
  const key = route.path.replace("/platform-admin/", "").replace("/platform-admin", "");
  const data = platformProfiles[key];
  if (!data) return null;
  const [job, primary, noun] = data;
  const kind = key === "topology" ? "topology" : key.includes("acceptance") || key === "operations" ? "checklist" : key === "permissions" || key === "api-coverage" ? "matrix" : key === "logs" ? "audit" : key === "content" ? "approval" : key === "releases" ? "rules" : key.includes(":") ? "docket" : "admin";
  return [job, primary, "查看记录", kind, [noun, "异常与影响", "变更记录"]];
}


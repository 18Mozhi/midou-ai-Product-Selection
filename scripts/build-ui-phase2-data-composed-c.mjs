import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = "design-plans/ui-phase-2-2026-09-07/design";
assert.ok(process.argv.slice(2).every((v) => v === "--write"));
const write = process.argv.includes("--write");
const read = async (file) =>
  (await readFile(path.join(repo, file), "utf8")).replaceAll("\r\n", "\n");
const output = async (name, value, parser) => {
  const file = path.join(repo, base, "data-composed-direction-c", name);
  const expected = await format(value, { ...(await resolveConfig(file)), parser });
  if (write) await writeFile(file, expected);
  else assert.equal(await read(path.relative(repo, file)), expected, name);
};
const templates = {};
for (const [key, controller] of [
  ["records", "records"],
  ["quality", "quality"],
]) {
  const dir = `${base}/data-${key}-direction-c`;
  const html = await read(`${dir}/index.html`);
  templates[key] = html
    .match(/<body>([\s\S]*?)<\/body>/)[1]
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, "");
  let css = await read(`${dir}/${controller}.css`);
  if (key === "records") {
    const imported = '@import url("../credential-assets-direction-c/credentials.css");';
    assert.ok(css.startsWith(imported));
    css = css.replace(
      imported,
      await read(`${base}/credential-assets-direction-c/credentials.css`),
    );
  }
  assert.ok(!css.includes("@import") && !css.includes("url("));
  // Mechanical component scoping only; old proposal files and controllers remain unchanged.
  css = css
    .replaceAll(":root", ":host")
    .replace(/(?<![\w-])body(?![\w-])/g, "[data-component-body]");
  await output(`${key}-scoped.css`, css, "css");
  await output(
    `${key}-scoped.js`,
    `// Generated by scripts/build-ui-phase2-data-composed-c.mjs.\nwindow.DATA_COMPOSED_MOUNT_${key.toUpperCase()} = function(document, history, location, scrollTo) {\n${await read(`${dir}/${controller}.js`)}\n};`,
    "babel",
  );
}
await output(
  "templates.js",
  `// Generated from the two unchanged proposal documents.\nwindow.DATA_COMPOSED_TEMPLATES = ${JSON.stringify(templates)};`,
  "babel",
);
console.log(`data_composed generated scope ${write ? "written" : "verified"}`);

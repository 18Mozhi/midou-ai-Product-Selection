import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const folder = "design-plans/ui-phase-2-2026-09-07";
const root = path.join(repo, folder);
const check = process.argv.includes("--check");
assert.ok(process.argv.slice(2).every((arg) => ["--write", "--check"].includes(arg)));
assert.equal(process.argv.slice(2).length, 1, "Use --write or --check");
const inputs = {};
async function read(relative) {
  const bytes = await readFile(path.join(repo, relative));
  inputs[relative] = createHash("sha256").update(bytes).digest("hex");
  return JSON.parse(bytes.toString("utf8"));
}
async function link(relative) {
  assert.equal(typeof relative, "string");
  const absolute = path.resolve(repo, relative);
  assert.ok(absolute.startsWith(repo + path.sep), `Out-of-repository link: ${relative}`);
  await access(absolute);
  return path.relative(root, absolute).split(path.sep).map(encodeURIComponent).join("/");
}
async function optionalLink(relative) {
  try {
    return await link(relative);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return null;
  }
}
const audit = await read(`${folder}/design-delivery-audit.json`);
assert.equal(audit.summary.routes, 73);
for (const key of ["sourceDrift", "pngDrift", "unmanifestedPng"])
  assert.equal(audit.summary[key], 0, `Resolve design audit ${key} first`);
const packages = {};
for (const item of audit.packages) {
  // The source audit remains authoritative; this entry only associates review materials.
  await read(item.evidence);
  assert.equal(inputs[item.evidence], item.manifestHash, `Stale audit: ${item.folder}`);
  const directory = path.posix.dirname(item.readme);
  packages[item.folder] = {
    id: item.folder,
    role: item.role,
    screenshots: item.screenshotCount,
    readme: await link(item.readme),
    evidence: await link(item.evidence),
    prototype: await optionalLink(`${directory}/index.html`),
    gallery: await optionalLink(`${directory}/gallery.html`),
  };
}
const pages = [];
for (const page of audit.pages) {
  const actualVue = [];
  const registryPath = `${folder}/action-reviews/${page.id}.json`;
  let registry;
  try {
    await access(path.join(repo, registryPath));
    registry = await read(registryPath);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  for (const [key, value] of Object.entries(registry ?? {})) {
    if (!key.startsWith("actualVue") || !value?.evidence) continue;
    await read(value.evidence);
    actualVue.push({
      key,
      scope: value.scope,
      approval: value.approval,
      readme: await link(`${folder}/${value.review}`),
      evidence: await link(value.evidence),
      gallery: await link(`${path.posix.dirname(value.evidence)}/index.html`),
    });
  }
  assert.ok(page.proposalPackages.length > 0, `${page.id} lacks a proposal association`);
  for (const id of page.proposalPackages) assert.ok(packages[id], `Unknown package: ${id}`);
  pages.push({
    id: page.id,
    spec: await link(page.spec),
    packages: page.proposalPackages,
    actualVue,
  });
}
const payload = {
  schemaVersion: 1,
  scope: "current-linked-materials-not-full-page-acceptance",
  inputHashes: inputs,
  summary: audit.summary,
  pages,
  packages,
};
const output = `// Generated by scripts/build-ui-phase2-review-evidence.mjs; do not edit.\nwindow.SCOUTOPS_PHASE2_EVIDENCE = ${JSON.stringify(payload, null, 2)};\n`;
const target = path.join(root, "review-evidence.js");
if (check) assert.equal(await readFile(target, "utf8"), output, "Review evidence is stale");
else await writeFile(target, output, "utf8");
console.log(
  `review_evidence_${check ? "checked" : "written"} routes=${pages.length} packages=${Object.keys(packages).length} actualVue=${pages.reduce((sum, page) => sum + page.actualVue.length, 0)}`,
);

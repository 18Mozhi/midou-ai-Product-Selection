CREATE TABLE `platform_messages` (
  `id` CHAR(36) CHARACTER SET ascii NOT NULL,
  `kind` ENUM('notification','email') NOT NULL,
  `title` VARCHAR(200) NOT NULL,
  `body` VARCHAR(2000) NOT NULL,
  `category` ENUM('task','approval','competitor','system') NOT NULL DEFAULT 'system',
  `severity` ENUM('info','warning','critical') NOT NULL DEFAULT 'info',
  `audience_type` ENUM('all_users','organization','user') NOT NULL,
  `organization_id` CHAR(36) CHARACTER SET ascii NULL,
  `user_id` CHAR(36) CHARACTER SET ascii NULL,
  `in_app_enabled` TINYINT(1) NOT NULL DEFAULT 1,
  `email_enabled` TINYINT(1) NOT NULL DEFAULT 0,
  `status` ENUM('draft','published','cancelled') NOT NULL DEFAULT 'draft',
  `version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_by` CHAR(36) CHARACTER SET ascii NOT NULL,
  `updated_by` CHAR(36) CHARACTER SET ascii NOT NULL,
  `published_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL,
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_platform_messages_kind_status` (`kind`,`status`,`updated_at`),
  KEY `idx_platform_messages_organization` (`organization_id`,`updated_at`),
  CONSTRAINT `fk_platform_message_organization` FOREIGN KEY (`organization_id`) REFERENCES `organizations` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_platform_message_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_platform_message_creator` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_platform_message_updater` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
